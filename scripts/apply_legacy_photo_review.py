def main():
    document = json.loads(ANNOTATIONS.read_text(encoding="utf-8"))
    filenames = used_filenames()
    if set(MASKS) != set(range(1, len(filenames) + 1)):
        raise SystemExit("Review table must cover every inventory index exactly once")
    for index, filename in enumerate(filenames, 1):
        record = document["photos"][filename]
        record["regions"] = MASKS[index]
        present = {region["kind"] for region in MASKS[index]}
        record["noVisible"] = sorted(KINDS - present)
        record["reviewed"] = True
        record["reviewedAt"] = "2026-10-23"
        record["reviewMethod"] = "full-set contact-sheet plus normalized-coordinate review"
    ANNOTATIONS.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Applied reviewed regions to {len(filenames)} photographs.")


if __name__ == "__main__":
    main()
